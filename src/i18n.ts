export function t(lang: Language, key: string, params?: Record<string, string>): string {
  const dictionary = translations[lang] || translations.sv;
  let text = dictionary[key] || translations.sv[key] || key;
  if (params) {
    Object.keys(params).forEach(pKey => {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), params[pKey]);
    });
  }
  return text;
}

import { getCachedTranslation } from './translationCache';

export function translateQuestion(
  qId: string, 
  defaultText: string, 
  defaultOptions: string[], 
  lang: Language, 
  origLang: Language = 'sv'
): { text: string; options: string[] } {
  if (lang === origLang) {
    return { text: defaultText, options: defaultOptions };
  }
  const qTrans = defaultQuestionTranslations[qId]?.[lang];
  if (qTrans) {
    return {
      text: qTrans.text,
      options: qTrans.options || defaultOptions
    };
  }
  const cached = getCachedTranslation({
    id: qId,
    text: defaultText,
    options: defaultOptions,
    correctAnswers: [],
    originalLanguage: origLang
  }, lang);
  if (cached) {
    return cached;
  }
  return { text: defaultText, options: defaultOptions };
}
